const CH = [1, 2, 3, 4, 5, 6].map(ch);

export function stageAt(T: number): Stage {
  const [X, Y, z, r, w, h] = CH.map((keys) => track(T, keys));
  return {X, Y, z, r, w, h};
}

// 箱の中の位置（0..1）→ 画面座標（回転を無視。文字を箱の領域に合わせるのは r≈0 のカットだけ）
export function boxPoint(s: Stage, u: number, v: number): [number, number] {
  return [s.X + (u - 0.5) * s.w * s.z, s.Y + (v - 0.5) * s.h * s.z];
}

