export type Pose = {p: V3; s: number; op: number};
// 採用ページ（side 0 = 発表用・左、1 = 読む資料・右）。O5 からの相対
export function pagePose(T: number, side: 0 | 1): Pose {
  const t = T - S['05'];
  const from: V3 = [TILE.cx, (side === 0 ? TILE.yTop : TILE.yBot) + TILE.cellY, 0.86];
  const f1 = sstep(t, 9.3, 9.9) - sstep(t, 11.5, 12.0);
  const f2 = sstep(t, 11.6, 12.2) - sstep(t, 14.2, 14.7);
  const z = 1.5 + (side === 0 ? 1.1 * f1 - 0.9 * f2 : 0.9 * f2 - 0.9 * f1);
  // 手前へ出る面は、画面の外へ逃げないよう中央へ寄せる
  const cx = side === 0 ? 0.62 * f1 - 0.35 * f2 : -0.3 * f2 + 0.2 * f1;
  const lift = inOut(prog(t, 14.4, 15.1));
  const to: V3 = [4 + cx + (side === 0 ? -3.95 : 3.95) * lerp(1, 0.94, lift), 0.2 + 0.95 * lift, z];
  const a = 6.25 + side * 0.15;
  const k = inOut(prog(t, a, a + 1.15));
  let p = l3(from, to, k);
  let s = lerp(TILE.cellW / PAGE.w, lerp(1, 0.9, lift), k);
  let op = t >= 6.2 ? 1 : 0;
  // 退場: 左は左へ抜け、右は 06 の文章のまとまりの場所へ下りながら消える
  const x = prog(t, 19.25, 20.15);
  if (x > 0) {
    if (side === 0) {
      p = add(p, -22 * in3(x), 0.5 * x, 0);
      op = 1 - sstep(x, 0.6, 1);
    } else {
      p = l3(p, [16.6, -1.5, 0], inOut(x));
      s = lerp(s, 1.0, x);
      op = 1 - sstep(x, 0.25, 0.95);
    }
  }
  return {p, s, op};
}
