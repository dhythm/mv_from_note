total = 0.0
starts = {}
for c in tl['cuts']:
    starts[c['id']] = (total, c['dur'])
    total += c['dur']
LOGO = total


def mmss(t):
    return f'{int(t // 60)}:{t % 60:04.1f}'


def frame(name, t):
    out = FR / f'{name}.webp'
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-ss', f'{t:.3f}', '-i', str(ROOT / 'out' / 'final.mp4'), '-frames:v', '1', '-vf', 'scale=1280:720', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-'], capture_output=True, check=True).stdout
    Image.frombytes('RGB', (1280, 720), raw).save(out, 'WEBP', quality=82)
    return f'assets/frames/{name}.webp'


