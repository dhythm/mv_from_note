// ---- 折れた線（0 から 100 へ） ----
export function jagAt(T: number): {head: number; amp: number; gray: number; o: number} {
  const c = L('03', T);
  const d = L('04', T);
  const e = L('05', T);
  if (T < S['04']) return {head: 100 * in3(prog(c, 5.6, 7.9)) ** 0.75, amp: 1, gray: 0, o: 1};
  if (d < 0.7) return {head: 100, amp: 1 - outExpo(prog(d, 0, 0.5)), gray: 0, o: 1 - prog(d, 0.3, 0.6)};
  if (T >= S['05'] && e < 3.4) return {head: 100 * outExpo(prog(e, 0.5, 1.4)), amp: 0.75 * (1 - outBack(prog(e, 1.75, 2.1))), gray: sstep(e, 1.8, 2.3), o: 1 - prog(e, 2.6, 3.3)};
  return {head: 0, amp: 0, gray: 0, o: 0};
}

// ---- 帯（実物＝墨、AI＝青、人の手＝墨）。[from, to, 色の種類, 列] ----
export type Bar = {a: number; b: number; kind: 'ink' | 'blue'; z: number; lift?: number};
export function barsAt(T: number): Bar[] {
  const out: Bar[] = [];
  const d = L('04', T);
  const e = L('05', T);
  if (T < S['04'] || T >= S['06']) return out;
  // 04: 70 → 90 の青い矢印（05 でも残る）
  out.push({a: 70, b: lerp(70, 90, inOut(prog(d, 4.9, 6.9))), kind: 'blue', z: LANE_Z});
  if (e > 0) {
    out.push({a: 0, b: 70 * outExpo(prog(e, 2.9, 4.1)), kind: 'ink', z: LANE_Z});
    out.push({a: 0, b: 70 * outExpo(prog(e, 9.4, 10.6)), kind: 'blue', z: LANE_Z + LANE_B});
    out.push({a: 70, b: 70 + 30 * outExpo(prog(e, 11.0, 12.1)), kind: 'ink', z: LANE_Z + LANE_B});
  }
  return out;
}
// 70〜90 の光
export const lightAt = (T: number) => {
  const d = L('04', T);
  const e = L('05', T);
  if (T < S['04'] || T >= S['06']) return 0;
  return inOut(prog(d, 4.9, 6.9)) * (e > 0 ? 1 - 0.5 * sstep(e, 0, 1) : 1);
};
// 図の層の濃さ（文字だけの場面では沈める）
export const figO = (T: number) => {
  if (T >= S['07'] && T < S['08']) return 1 - prog(L('07', T), 0, 0.35);
  if (T >= S['08'] && T < S['09']) return prog(L('08', T), 0, 0.25);
  if (T >= S['09'] && T < S['10']) return lerp(1, 0.3, sstep(L('09', T), 3.0, 3.6));
  if (T >= S['10']) return lerp(0.3, 1, prog(L('10', T), 0, 0.3));
  return 1;
};
