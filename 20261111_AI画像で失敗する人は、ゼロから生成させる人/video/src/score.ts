// ---- グラス ----
export function glassAt(T: number): GlassS {
  const g: GlassS = {x: GH[0], y: 0, z: GH[2], ry: 0.3 + T * 0.12, s: 1, wob: 0, lie: 0, gloss: 0, glow: 0, cherry: 0};
  if (T < S['04']) {
    const a = L('01', T);
    const b = L('02', T);
    const c = L('03', T);
    g.wob = kv(a, [[1.7, 0], [3.2, 0.3, out3]]) * kv(b, [[0, 1], [0.8, 0.45], [4.6, 0.45], [6.0, 0.7], [9.0, 0.7], [11, 0.5]]);
    g.lie = kv(b, [[6.5, 0], [8.3, 1, inOut]]);
    g.gloss = kv(b, [[9.2, 0], [10.2, 1, out3]]) * kv(c, [[0, 1], [2, 0.5]]);
    // 03: 矢印が着いた瞬間に大きく崩れる
    const hit = c - 7.9;
    if (hit > 0) {
      g.wob = 0.5 + 0.55 * clamp(hit * 6) + 0.25 * damped(c, 7.9, 1, 2.2, 3);
      g.sy = 1 + 0.18 * damped(c, 7.9, 1, 3, 5);
    }
    g.ry = 0.3 + T * 0.1;
    return g;
  }
  if (T < S['06']) {
    // 04: 実物として 70 に置く → 光 → 90 へ。05 の頭で退く
    const a = L('04', T);
    const e = L('05', T);
    if (a < 0.38) return {...g, wob: 1, lie: 1, s: 1};
    const slide = inOut(prog(a, 4.9, 6.9));
    g.x = lerp(SX(70), SX(90), slide);
    g.z = -1.25;
    const drop = prog(a, 0.38, 0.8);
    g.y = (1 - out3(drop)) * 5;
    g.sy = 1 - 0.16 * damped(a, 0.8, 1, 3.2, 6);
    g.sx = 1 + 0.1 * damped(a, 0.8, 1, 3.2, 6);
    g.glow = kv(a, [[2.5, 0], [3.2, 1, out3]]);
    g.gloss = 0.25 * g.glow;
    g.ry = -0.4 + a * 0.16;
    g.tilt = -0.07 * Math.sin(Math.PI * slide);
    g.s = e > 0 ? 1 - in3(prog(e, 0.1, 0.6)) : 1;
    return g;
  }
  if (T >= S['09'] && T < S['10']) {
    // 09: 崩れたまま出される
    const a = L('09', T);
    return {...g, lie: 1, wob: 0.75, gloss: 0.6, x: GH[0] + in3(prog(a, 2.9, 3.5)) * 16, sy: 1 - 0.1 * damped(a, 1.3, 1, 3, 5), s: a > 3.6 ? 0 : 1};
  }
  if (T >= S['10'] && T < S['11']) {
    const a = L('10', T);
    return {...g, y: 0.6, lie: kv(a, [[0, 0.55], [9.4, 0.55], [11.2, 1]]), wob: kv(a, [[0, 0.3], [9.4, 0.3], [11.2, 0.95, outBack]]), gloss: 0.5, s: outBack(prog(a, 0.2, 0.7)) * (1 - in3(prog(a, 16.7, 17)))};
  }
  if (T >= S['12']) {
    // 12: 90 の実物 → 人の手の帯の上を通って 100 へ。最後にさくらんぼ
    const a = L('12', T);
    const sl = inOut(prog(a, 3.3, 4.3));
    const ch = prog(a, 4.35, 4.8);
    return {...g, x: lerp(SX(90), SX(100), sl), z: -1.25, ry: 0.4 + a * 0.14, glow: 1, gloss: 0.25, cherry: a < 4.35 ? 0 : 0.02 + 0.98 * ch * ch, sy: 1 - 0.07 * damped(a, 4.8, 1, 4, 7), tilt: -0.06 * Math.sin(Math.PI * sl), s: outBack(prog(a, 0.1, 0.6))};
  }
  return {...g, s: 0};
}

